from inspect import cleandoc

__usage__ = cleandoc(
	"""
快速调用：
/今日B话榜 ————看看今天群友发了多少消息。

### 🎨一般用法

#### B话榜

-`/B话榜` ————看看有史以来（机器人存在以来）群友们发了多少消息！ （好像没写）

-`/今日B话榜` ————看看今天的群友发了多少消息！

-`/昨日B话榜` ————看看昨天的群友发了多少消息！

-`/本周B话榜` ————看看本周的群友发了多少消息！

-`/上周B话榜` ————看看上周的群友发了多少消息！

-`/本月B话榜` ————看看这个月的群友发了多少消息！

-`/年度B话榜` ————看看今年的群友发了多少消息！

-`/历史B话榜` ————看看历史上（机器人存在以来）的群友发了多少消息！

#### 看看B话（kkb）

-`/看看B话 [@某人|QQ号]` ————看看这个b人在这个b群发了多少b话！

#### 分布图

-`/B话榜分布` ————今天哪个时段最热闹（按小时）

-`/B话榜分布 本月 星期` ————这个月按星期几统计

-`/B话榜分布 本周 -g 群号` ————看别的群

#### 多群对比

-`/B话榜对比 123456 789012` ————两个群放一张图里对比

-`/B话榜对比 123456 789012 -t 本周` ————换个统计区间

#### 成员跨群

-`/B话榜成员 @某人` ————TA 在各个群一共说了多少

-`/B话榜成员 12345678 本月` ————只看这个月

#### 样式与模板

`/B话榜样式` ————列出所有配色和排版，附当前群用的

`/B话榜样式 浅色` ————渲一张预览图看看

`/B话榜样式 浅色 横排` ————配色和排版一起看

`/B话榜模板` ————列出所有模板（内置的 + 自己放的）

`/B话榜模板 podium` ————渲一张预览图

#### 群配置

`/B话榜配置 帮助` ————列出所有可配置项

`/B话榜配置` ————查看当前群的配置

`/B话榜配置 开关 关` ————关掉这个群的排行榜

`/B话榜配置 人数 3` ————只显示前 3 名

`/B话榜配置 样式 浅色` ————换配色

`/B话榜配置 模板 podium` ————换模板

`/B话榜配置 排除 123,456` ————统计时排除这几个人

`/B话榜配置 推送 开` ————给这个群开定时推送

`/B话榜重载` ————重新读取配置文件并刷新定时任务

### 🚀进阶用法

#### B话榜

`/{时间类型（今日|年度）?}{B话榜|废话榜} {时间类型？} {ISO8601 格式时间 ?} {群号} {关键词} [-m 模板]`

如：`/B话榜 历史 2024-01-01~2024-01-02 12345678 女装`

也可以 `/{时间类型（今日|年度）?}{B话榜|废话榜} {时间类型？} {ISO8601 格式时间 ?} -g {群号} -k {关键词}`

以下调用方法均合法：

`/今日B话榜 -g 12345678 -k 女装`
`/昨日B话榜 -k 女装`
`/本周B话榜 -g 12345678`
`/今日B话榜 -m podium`

#### 看看B话

`/看看B话 {@|QQ号} {群号？} {关键词？}`

以下调用方法均合法：

`/kkb 114514 1919810 ♂`
`/kkb @man -k ♂`

#### 分布 / 对比 / 成员

`/B话榜分布 {时间类型？} {小时|星期？} [-g 群号] [-k 关键词]`

`/B话榜对比 {群号} {群号} … [-t 时间类型] [-k 关键词]`

`/B话榜成员 {@|QQ号} {时间类型？}`

	"""
)
